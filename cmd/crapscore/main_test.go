func complexityOf(t *testing.T, body string) int {
	t.Helper()
	f, err := parser.ParseFile(token.NewFileSet(), "x.go", "package p\n"+body, 0)
	if err != nil {
		t.Fatal(err)
	}
	return Complexity(f.Decls[len(f.Decls)-1])
}

func TestComplexity(t *testing.T) {
	cases := []struct {
		name, src string
		want      int
	}{
		{"empty", `func f() {}`, 1},
		{"if", `func f(a int) { if a > 0 { } }`, 2},
		{"if else if", `func f(a int) { if a > 0 { } else if a < 0 { } else { } }`, 3},
		{"for range", `func f(a []int) { for range a { }; for i := 0; i < 3; i++ { } }`, 3},
		{"and or", `func f(a, b, c bool) bool { return a && b || c }`, 3},
		{"switch default not counted", `func f(a int) { switch a { case 1: case 2, 3: default: } }`, 3},
		{"select", `func f(c chan int) { select { case <-c: default: } }`, 2},
		{"closure counts", `func f(a bool) { g := func() { if a { } }; g() }`, 2},
		{"method", `type T struct{}; func (T) f(a bool) { if a || a { } }`, 3},
	}
	for _, c := range cases {
		if got := complexityOf(t, c.src); got != c.want {
			t.Errorf("%s: complexity %d, want %d", c.name, got, c.want)
		}
	}
}

func TestCRAPFormula(t *testing.T) {
	if got := CRAP(10, 1); got != 10 {
		t.Errorf("full coverage: %v", got)
	}
	if got := CRAP(5, 0); got != 30 {
		t.Errorf("zero coverage CC5: %v", got)
	}
	if got := CRAP(10, 0.5); math.Abs(got-22.5) > 1e-9 {
		t.Errorf("half coverage CC10: %v", got)
	}
}

const sample = `package p

func covered(a int) int {
	if a > 0 {
		return 1
	}
	return 2
}

func uncovered(a int) int {
	if a > 0 {
		return 1
	}
	return 2
}

func empty() {}
`

// setup builds a temp module with sample.go, a generated file and a test file.
func setup(t *testing.T, profile string) string {
	t.Helper()
	root := t.TempDir()
	must := func(name, s string) {
		p := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(s), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	must("go.mod", "module example.com/m\n\ngo 1.24\n")
	must("p/sample.go", sample)
	must("p/gen.go", "// Code generated by x. DO NOT EDIT.\n\npackage p\n\nfunc G(a bool) { if a { } }\n")
	must("p/sample_test.go", "package p\n\nfunc TestX(a bool) { if a { } }\n")
	must("nested/go.mod", "module nested\n")
	must("nested/n.go", "package n\n\nfunc N(a bool) { if a { } }\n")
	must("cover.out", profile)
	return root
}

// Blocks: covered() lines 4-6 and 7 (3 stmts: if, return, return), uncovered() 11-13 and 14.
const profile = `mode: set
example.com/m/p/sample.go:3.20,4.10 1 1
example.com/m/p/sample.go:4.10,6.3 1 1
example.com/m/p/sample.go:7.2,7.10 1 1
example.com/m/p/sample.go:10.24,11.10 1 0
example.com/m/p/sample.go:11.10,13.3 1 0
example.com/m/p/sample.go:14.2,14.10 1 0
`

func analyseSample(t *testing.T, root string, extra ...string) map[string]*Func {
	t.Helper()
	funcs, err := ParseTree(root)
	if err != nil {
		t.Fatal(err)
	}
	prof := Profile{}
	for _, p := range append([]string{"cover.out"}, extra...) {
		if err := prof.ReadProfileFile(filepath.Join(root, p)); err != nil {
			t.Fatal(err)
		}
	}
	prof.Apply("example.com/m", funcs)
	m := map[string]*Func{}
	for _, f := range funcs {
		m[f.Name] = f
	}
	return m
}

func TestCoverageMappingAndExclusions(t *testing.T) {
	m := analyseSample(t, setup(t, profile))
	if len(m) != 3 {
		t.Fatalf("want 3 functions (no generated/test/nested), got %d: %v", len(m), m)
	}
	if c := m["covered"]; c.Coverage != 1 || c.CRAP != 2 {
		t.Errorf("covered: %+v", c)
	}
	if u := m["uncovered"]; u.Coverage != 0 || u.CRAP != 6 {
		t.Errorf("uncovered: %+v", u)
	}
	if e := m["empty"]; e.Coverage != 1 {
		t.Errorf("empty func in profiled file should be fully covered: %+v", e)
	}
}

func TestMergeProfiles(t *testing.T) {
	root := setup(t, profile)
	extra := "mode: set\nexample.com/m/p/sample.go:10.24,11.10 1 1\nexample.com/m/p/sample.go:11.10,13.3 1 1\nexample.com/m/p/sample.go:14.2,14.10 1 1\n"
	if err := os.WriteFile(filepath.Join(root, "extra.out"), []byte(extra), 0o644); err != nil {
		t.Fatal(err)
	}
	if u := analyseSample(t, root, "extra.out")["uncovered"]; u.Coverage != 1 {
		t.Errorf("merge should cover: %+v", u)
	}
}

