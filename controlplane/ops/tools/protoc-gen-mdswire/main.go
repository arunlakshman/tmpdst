// Command protoc-gen-mdswire is a protoc plugin. It writes the plain value types
// of the control-plane contract and the code that converts them to and from the
// generated api messages, so the .proto files are the one source and nothing is
// translated by hand.
//
// The custom options of api/controlplane/options/v1/options.proto
// say which messages it writes and how, and the leading comment of a message is
// the doc comment of its struct. buf runs the plugin (see buf.gen.yaml) with the
// output directory internal/controlplane, and it writes:
//
//	contract/wire_types_gen.go   the structs of package contract (no wire import)
//	domain/rebalance/wire_types_gen.go  the structs of package rebalance (no wire import)
//	wire/wire_gen.go             <Message>ToCore and <Message>FromCore
//
// The value types stay plain: they are compared, hashed and used as map keys by
// the deterministic core, which must not import protobuf.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/reflect/protoregistry"
	"google.golang.org/protobuf/types/dynamicpb"
)

const header = "// Code generated by protoc-gen-mdswire from the .proto files in api. DO NOT EDIT.\n\n"

// optionsPackage is the proto package of options.proto.
const optionsPackage = "controlplane.options.v1"

const module = "github.com/manifesterio/mds/controlplane"

// goPackages are the Go packages that the options may name, with their import paths.
var goPackages = map[string]string{
	"contract":  module + "/internal/controlplane/contract",
	"rebalance": module + "/internal/controlplane/domain/rebalance",
	"runtime":   module + "/internal/runtime",
}

// structFiles are the files that hold the structs of each package, under the
// output directory.
var structFiles = map[string]string{
	"contract":  "contract/wire_types_gen.go",
	"rebalance": "domain/rebalance/wire_types_gen.go",
}

const wireFile = "wire/wire_gen.go"

// goKinds are the field kinds the plugin knows, with their Go types. An enum
// field takes its Go type from go_type.
var goKinds = map[protoreflect.Kind]string{
	protoreflect.StringKind:  "string",
	protoreflect.Int32Kind:   "int32",
	protoreflect.Int64Kind:   "int64",
	protoreflect.BoolKind:    "bool",
	protoreflect.BytesKind:   "[]byte",
	protoreflect.MessageKind: "",
	protoreflect.EnumKind:    "",
}

func main() {
	protogen.Options{}.Run(generate)
}

// message is a message with go_struct or go_existing.
type message struct {
	m          *protogen.Message
	goType     string // the Go type with its package, such as contract.CommitSegment
	write      bool   // go_struct: the plugin writes the struct
	converters bool   // the plugin writes <Message>ToCore and <Message>FromCore
	alias      string // the name of the message's api package in package wire
	fields     []field
}

// field is one field of a message, with its Go side.
type field struct {
	f      *protogen.Field
	goName string // the name in the Go type, such as TopicPartition
	goType string // go_type, or ""
	embed  bool
	msg    *message // the message type of a message field
}

func generate(gen *protogen.Plugin) error {
	opts, err := newOptions(gen)
	if err != nil {
		return err
	}
	msgs, err := readMessages(gen, opts)
	if err != nil {
		return err
	}
	for _, pkg := range slices.Sorted(maps.Keys(structFiles)) {
		src, err := structs(msgs, pkg)
		if err != nil {
			return err
		}
		if _, err := gen.NewGeneratedFile(structFiles[pkg], "").Write(src); err != nil {
			return err
		}
	}
	src, err := converters(msgs)
	if err != nil {
		return err
	}
	_, err = gen.NewGeneratedFile(wireFile, "").Write(src)
	return err
}

// readMessages finds the messages with go_struct or go_existing, in the order of
// the files in the request and of the messages in each file.
func readMessages(gen *protogen.Plugin, opts *options) ([]*message, error) {
	var msgs []*message
	byName := map[protoreflect.FullName]*message{}
	for _, file := range gen.Files {
		if !file.Generate {
			continue
		}
		fileOpts, err := opts.read(file.Desc.Options())
		if err != nil {
			return nil, err
		}
		for _, m := range file.Messages {
			msg, err := readMessage(opts, file, m)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", m.Desc.FullName(), err)
			}
			if msg == nil {
				continue
			}
			msg.converters = !opts.flag(fileOpts, "no_converters")
			msgs = append(msgs, msg)
			byName[m.Desc.FullName()] = msg
		}
	}
	for _, msg := range msgs {
		for _, f := range msg.m.Fields {
			fd, err := readField(opts, f, byName)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", f.Desc.FullName(), err)
			}
			msg.fields = append(msg.fields, fd)
		}
	}
	return msgs, nil
}

// readMessage reads the options of one message. It returns nil for a message
// without go_struct or go_existing.
func readMessage(opts *options, file *protogen.File, m *protogen.Message) (*message, error) {
	mo, err := opts.read(m.Desc.Options())
	if err != nil {
		return nil, err
	}
	st, ex := opts.text(mo, "go_struct"), opts.text(mo, "go_existing")
	switch {
	case st == "" && ex == "":
		return nil, nil
	case st != "" && ex != "":
		return nil, errors.New("go_struct and go_existing are both set")
	}
	msg := &message{
		m:      m,
		goType: st + ex,
		write:  st != "",
		// The rest of the code imports controlplanev1 as cpv1, so package wire does too.
		alias: strings.Replace(string(file.GoPackageName), "controlplane", "cp", 1),
	}
	if err := checkType(msg.goType, msg.write); err != nil {
		return nil, err
	}
	return msg, nil
}

func readField(opts *options, f *protogen.Field, byName map[protoreflect.FullName]*message) (field, error) {
	fo, err := opts.read(f.Desc.Options())
	if err != nil {
		return field{}, err
	}
	fd := field{
		f:      f,
		goName: opts.text(fo, "go_name"),
		goType: opts.text(fo, "go_type"),
		embed:  opts.flag(fo, "go_embed"),
	}
	if fd.goName == "" {
		fd.goName = goName(string(f.Desc.Name()))
	}
	kind := f.Desc.Kind()
	if _, ok := goKinds[kind]; !ok {
		return field{}, fmt.Errorf("kind %s is not supported by protoc-gen-mdswire", kind)
	}
	if fd.goType != "" {
		if err := checkType(fd.goType, false); err != nil {
			return field{}, err
		}
	}
	switch kind {
	case protoreflect.EnumKind:
		if fd.goType == "" {
			return field{}, errors.New("an enum field needs go_type")
		}
	case protoreflect.MessageKind:
		fd.msg = byName[f.Message.Desc.FullName()]
		if fd.msg == nil {
			return field{}, fmt.Errorf("message %s has no go_struct or go_existing", f.Message.Desc.FullName())
		}
	}
	return fd, nil
}

// checkType checks that a Go type of an option names a package the plugin
// knows. A struct the plugin writes must be in a package with a struct file.
func checkType(t string, write bool) error {
	pkg, _, ok := strings.Cut(t, ".")
	if !ok {
		return fmt.Errorf("the Go type %q has no package", t)
	}
	if _, ok := structFiles[pkg]; write && !ok {
		return fmt.Errorf("go_struct %q: the plugin writes structs only in contract and rebalance", t)
	}
	if _, ok := goPackages[pkg]; !ok {
		return fmt.Errorf("the Go type %q: unknown package %s", t, pkg)
	}
	return nil
}

// goName is a proto field name in Go style, where "id" is an initialism:
// member_id -> MemberID.
func goName(name string) string {
	var b strings.Builder
	for part := range strings.SplitSeq(name, "_") {
		switch part {
		case "":
		case "id":
			b.WriteString("ID")
		default:
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

// doc turns the leading comment of message msgName into the doc comment of its
// Go type. A comment that starts with the message name starts with the Go name
// instead.
func doc(comment, msgName, goName string) string {
	c := comment
	if rest, ok := strings.CutPrefix(c, " "+msgName+" "); ok {
		c = " " + goName + " " + rest
	}
	return protogen.Comments(c).String()
}

// goFile collects the body of one generated Go file and the packages it uses.
type goFile struct {
	pkg     string
	body    bytes.Buffer
	imports map[string]string // import path -> name to import it as ("" for none)
}

// ref is the Go type t (such as contract.Offset) as package f writes it. It
// notes the import that t needs.
func (f *goFile) ref(t string) string {
	pkg, name, _ := strings.Cut(t, ".")
	if pkg == f.pkg {
		return name
	}
	f.imports[goPackages[pkg]] = ""
	return t
}

// typeOf is the Go type of a field in the value type, as package f writes it.
func (f *goFile) typeOf(fd field) string {
	t := goKinds[fd.f.Desc.Kind()]
	switch {
	case fd.goType != "":
		t = f.ref(fd.goType)
	case fd.msg != nil:
		t = f.ref(fd.msg.goType)
	}
	if fd.f.Desc.IsList() {
		return "[]" + t
	}
	return t
}

// source is the formatted Go source of the file.
func (f *goFile) source(extra string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header + "package " + f.pkg + "\n\n")
	if len(f.imports) > 0 {
		b.WriteString("import (\n")
		for _, path := range slices.Sorted(maps.Keys(f.imports)) {
			if path == "slices" {
				b.WriteString("\t\"slices\"\n\n")
			}
		}
		for _, path := range slices.Sorted(maps.Keys(f.imports)) {
			if path != "slices" {
				fmt.Fprintf(&b, "\t%s %q\n", f.imports[path], path)
			}
		}
		b.WriteString(")\n\n")
	}
	b.WriteString(extra)
	b.Write(f.body.Bytes())
	return format.Source(b.Bytes())
}

// structs writes the structs of package pkg.
func structs(msgs []*message, pkg string) ([]byte, error) {
	f := &goFile{pkg: pkg, imports: map[string]string{}}
	for _, msg := range msgs {
		if !msg.write || !strings.HasPrefix(msg.goType, pkg+".") {
			continue
		}
		name := f.ref(msg.goType)
		f.body.WriteString(doc(string(msg.m.Comments.Leading), string(msg.m.Desc.Name()), name))
		fmt.Fprintf(&f.body, "type %s struct {\n", name)
		for _, fd := range msg.fields {
			if fd.embed {
				fmt.Fprintf(&f.body, "\t%s\n", f.typeOf(fd))
				continue
			}
			fmt.Fprintf(&f.body, "\t%s %s\n", fd.goName, f.typeOf(fd))
		}
		f.body.WriteString("}\n\n")
	}
	return f.source("")
}

// mapSlice is written once at the top of package wire.
const mapSlice = `// mapSlice converts every element. An empty input gives nil, the same as a loop
// that appends to a nil slice.
func mapSlice[From, To any](in []From, convert func(From) To) []To {
	if len(in) == 0 {
		return nil
	}
	out := make([]To, len(in))
	for i, item := range in {
		out[i] = convert(item)
	}
	return out
}

`

// converters writes <Message>ToCore and <Message>FromCore for every message that
// has converters.
func converters(msgs []*message) ([]byte, error) {
	f := &goFile{pkg: "wire", imports: map[string]string{}}
	seen := map[string]bool{}
	for _, msg := range msgs {
		if !msg.converters {
			continue
		}
		name := msg.m.GoIdent.GoName
		// The converters are named after the short message name, so two messages
		// with converters must not share it.
		if seen[name] {
			return nil, fmt.Errorf("two messages with converters are called %s", name)
		}
		seen[name] = true
		f.imports[string(msg.m.GoIdent.GoImportPath)] = msg.alias
		q := f.ref(msg.goType)
		gm := msg.alias + "." + name
		fmt.Fprintf(&f.body, "// %sToCore rebuilds a %s from a %s message.\nfunc %sToCore(m *%s) %s {\n\treturn %s{\n", name, q, name, name, gm, q, q)
		for _, fd := range msg.fields {
			fmt.Fprintf(&f.body, "\t\t%s: %s,\n", fd.key(), f.toCore(fd))
		}
		f.body.WriteString("\t}\n}\n\n")
		fmt.Fprintf(&f.body, "// %sFromCore builds a %s message from a %s.\nfunc %sFromCore(v %s) *%s {\n\treturn &%s{\n", name, name, q, name, q, gm, gm)
		for _, fd := range msg.fields {
			fmt.Fprintf(&f.body, "\t\t%s: %s,\n", fd.f.GoName, f.fromCore(fd))
		}
		f.body.WriteString("\t}\n}\n\n")
	}
	return f.source(mapSlice)
}

// key is the name of the field in a composite literal of the Go type.
func (fd field) key() string {
	if fd.embed {
		_, name, _ := strings.Cut(fd.msg.goType, ".")
		return name
	}
	return fd.goName
}

// toCore is the expression that converts field fd of the message m.
func (f *goFile) toCore(fd field) string {
	get := "m.Get" + fd.f.GoName + "()"
	kind, list := fd.f.Desc.Kind(), fd.f.Desc.IsList()
	switch {
	case kind == protoreflect.EnumKind && list:
		return fmt.Sprintf("mapSlice(%s, %sToCore)", get, fd.f.Enum.GoIdent.GoName)
	case kind == protoreflect.EnumKind:
		return fd.f.Enum.GoIdent.GoName + "ToCore(" + get + ")"
	case kind == protoreflect.MessageKind && list:
		return fmt.Sprintf("mapSlice(%s, %sToCore)", get, fd.f.Message.GoIdent.GoName)
	case kind == protoreflect.MessageKind:
		return fmt.Sprintf("%sToCore(%s)", fd.f.Message.GoIdent.GoName, get)
	case list || kind == protoreflect.BytesKind:
		f.imports["slices"] = ""
		return "slices.Clone(" + get + ")"
	case fd.goType != "":
		return f.ref(fd.goType) + "(" + get + ")"
	}
	return get
}

// fromCore is the expression that converts field fd of the Go value v.
func (f *goFile) fromCore(fd field) string {
	v := "v." + fd.key()
	kind, list := fd.f.Desc.Kind(), fd.f.Desc.IsList()
	switch {
	case kind == protoreflect.EnumKind && list:
		return fmt.Sprintf("mapSlice(%s, %sFromCore)", v, fd.f.Enum.GoIdent.GoName)
	case kind == protoreflect.EnumKind:
		return fd.f.Enum.GoIdent.GoName + "FromCore(" + v + ")"
	case kind == protoreflect.MessageKind && list:
		return fmt.Sprintf("mapSlice(%s, %sFromCore)", v, fd.f.Message.GoIdent.GoName)
	case kind == protoreflect.MessageKind:
		return fmt.Sprintf("%sFromCore(%s)", fd.f.Message.GoIdent.GoName, v)
	case list || kind == protoreflect.BytesKind:
		f.imports["slices"] = ""
		return "slices.Clone(" + v + ")"
	case fd.goType != "":
		return goKinds[kind] + "(" + v + ")"
	}
	return v
}

// options reads the custom options of options.proto. The plugin cannot import
// the Go code of options.proto, because buf writes that code in the same run, so
// it reads the options through the descriptors in the request.
type options struct {
	types *protoregistry.Types
	ext   map[string]protoreflect.ExtensionTypeDescriptor // by short name, such as go_struct
}

func newOptions(gen *protogen.Plugin) (*options, error) {
	o := &options{types: new(protoregistry.Types), ext: map[string]protoreflect.ExtensionTypeDescriptor{}}
	for _, file := range gen.Files {
		if file.Desc.Package() != optionsPackage {
			continue
		}
		exts := file.Desc.Extensions()
		for i := range exts.Len() {
			xt := dynamicpb.NewExtensionType(exts.Get(i))
			if err := o.types.RegisterExtension(xt); err != nil {
				return nil, err
			}
			o.ext[string(exts.Get(i).Name())] = xt.TypeDescriptor()
		}
	}
	for _, name := range []string{"no_converters", "go_struct", "go_existing", "go_name", "go_type", "go_embed"} {
		if o.ext[name] == nil {
			return nil, fmt.Errorf("option %s.%s not found: does the .proto import options.proto?", optionsPackage, name)
		}
	}
	return o, nil
}

// read parses the custom options in the options of a descriptor. In the request
// they are unknown fields, as the plugin binary does not know them.
func (o *options) read(opts protoreflect.ProtoMessage) (protoreflect.Message, error) {
	b, err := proto.Marshal(opts)
	if err != nil {
		return nil, err
	}
	m := opts.ProtoReflect().Type().New()
	if err := (proto.UnmarshalOptions{Resolver: o.types}).Unmarshal(b, m.Interface()); err != nil {
		return nil, err
	}
	return m, nil
}

// text is the value of a string option, or "" when it is not set.
func (o *options) text(m protoreflect.Message, name string) string {
	return m.Get(o.ext[name]).String()
}

// flag is the value of a bool option, or false when it is not set.
func (o *options) flag(m protoreflect.Message, name string) bool {
	return m.Get(o.ext[name]).Bool()
}
